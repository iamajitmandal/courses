# arithmetic operators : +, -, *, /, %

# String data type
a = "Nepal"

# Boolean data type
age = 20
print(age >= 18)

# None data type
name = None
print(name) # gives 'None'

# input() function: always gives string so, we use int() to read integers
a = input("Enter your name")
print(a)

# calculator function
x = input('Enter first number')
y = input('Enter second number')
sum = x + y # concatenates two string
print(sum) # gives 1 + 2 = 12 not 3 in this case

# above program adds two strings
# corrected code
x = int(input('Enter first number'))
y = int(input('Enter second number'))
sum = x + y
print(sum)

