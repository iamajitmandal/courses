# Pandas:
# Pandas is a fast, powerful, and open-source Python library used primarily for data manipulation, cleaning, and analysis.
# It provides intuitive structures to handle tabular data efficiently, acting like a highly programmable spreadsheet or SQL
# table directly inside Python

# Key Benefits
# Handles Heavy Data: Built on top of NumPy, it easily processes large files.
# File Flexibility: Reads and writes data across CSV, Excel, JSON, and SQL databases.
# Built-in Cleaning: Features tools to drop missing values, find duplicates, and filter outliers.

# Core Data Structures
# Pandas operates on two main data structures:
# Data Structure    Dimensions          Description                                    Visual Analogy
# Series                1DA         single column of labeled data.                  An Excel column.
# DataFrame             2DA         tabular structure with rows and columns.        An entire Excel spreadsheet.