# Exploratory Data Analysis (EDA) is a foundational process used by data scientists to analyze datasets,
# summarize their main characteristics, and uncover hidden patterns. Rather than jumping straight into complex
# modeling, analysts use statistical summaries and data visualization (like scatter plots and histograms) to detect
# anomalies, spot missing values, and test initial assumptions. It helps ensure that the statistical methods and
# machine learning models selected are appropriate for the data.
