# Alan Turing(1950):
# Turing Test: The Turing Test is a method to check if a machine can show human-like intelligence
# through conversation. English mathematician Alan Turing proposed the test in 1950 in his paper
# "Computing Machinery and Intelligence". He originally called it the "Imitation Game".

# How the Test Works?
# Three Players: The test uses a human judge (the interrogator), another human, and a machine.
# Text Chat: All three players stay in separate rooms and talk only through text-based messages.
# The Goal: The judge asks questions to both participants to figure out which one is the human and
# which one is the machine.
# Passing the Test: If the judge cannot tell the machine and the human apart based on their answers,
# the machine passes.

