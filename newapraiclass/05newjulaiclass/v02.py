# Supervised Learning: Supervised learning is a machine learning technique where an AI model is trained on labeled datasets.
# The algorithm learns to map input features to known, correct output "labels," allowing it to identify patterns,
# iteratively improve its accuracy over time, and predict outcomes for entirely new, unseen data.

# Continuous & Discrete:
# Discrete data is countable and limited to distinct, separate whole values (e.g., number of cars, dice rolls).
# Continuous data is measurable and can take on any value within a range, including infinite decimals (e.g., temperature, height, time).

# Supervised learning is primarily used for two main types of problems:
# Classification: Used to predict discrete categories or classes (e.g., classifying an email as "Spam" or "Not Spam," or
# identifying if a tumor is "Benign" or "Malignant").
#
# Regression: Used to forecast or predict continuous numerical values (e.g., predicting the price of a house based on
# its size and location, or forecasting next quarter's sales).

# Linear Regression: Linear regression is a statistical and machine learning method used to model the relationship between a dependent variable and
# one or more independent variables. It finds the "line of best fit" by minimizing the errors between predicted and actual values, allowing you to
# make future predictions.

